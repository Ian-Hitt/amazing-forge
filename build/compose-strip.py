#!/usr/bin/env python3
"""Composite the chapter-opener film strip: one FIXED frame, swappable scenes.

The opener motif is a horizontal film strip with three scene windows. Instead of
regenerating the whole banner per chapter (which drifts — the model redraws the
strip geometry every time), we draw the strip HERE in code (byte-identical every
call) and paste three small scene vignettes into the three fixed windows. Only
the scenes change chapter to chapter; the container never does.

Vignettes come from build/art/V*.png (generated by gen-art.py, square 1:1).

Use:
    ./build/compose-strip.py --scenes V1,V2,V3 --out build/art/O1-the-roll.png
    ./build/compose-strip.py --scenes V4,V5,V6 --out /tmp/sample-b.png
"""
from __future__ import annotations
import argparse, sys
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "build" / "art"

# ---- banner geometry (21:9, high-res so it stays crisp at ~4.35in on the page) --
W, H = 2520, 1080
CHARCOAL = (26, 26, 26, 255)        # matches lib.typ `ink`
PAPER = (255, 255, 255, 255)        # window fill (page is pure white)

STRIP_MARGIN_Y = 24                 # gap above/below the strip body
SPROCKET_BAND = 150                 # height of each sprocket-hole row
HOLE_W, HOLE_H, HOLE_GAP = 62, 84, 96
WIN_COUNT = 3
WIN_SIZE = 700                      # square windows
WIN_BORDER = 7


def draw_strip() -> tuple[Image.Image, list[tuple[int, int]]]:
    """Return (banner with empty strip drawn, list of window top-left origins)."""
    img = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)

    # strip body
    top, bot = STRIP_MARGIN_Y, H - STRIP_MARGIN_Y
    d.rounded_rectangle([0, top, W - 1, bot], radius=18, fill=CHARCOAL)

    # window band, centered vertically; 3 evenly spaced square windows
    band_top = top + SPROCKET_BAND
    band_bot = bot - SPROCKET_BAND
    win_y = band_top + (band_bot - band_top - WIN_SIZE) // 2
    total_win = WIN_COUNT * WIN_SIZE
    gap = (W - total_win) // (WIN_COUNT + 1)
    origins = []
    for k in range(WIN_COUNT):
        x = gap + k * (WIN_SIZE + gap)
        d.rectangle([x, win_y, x + WIN_SIZE, win_y + WIN_SIZE], fill=PAPER)
        origins.append((x, win_y))

    # sprocket holes: rounded rects knocked out (paper) top & bottom, aligned to a
    # steady pitch across the whole width so the perforation reads as real film
    pitch = HOLE_W + HOLE_GAP
    n = W // pitch
    left = (W - (n * pitch - HOLE_GAP)) // 2
    for row_cy in (top + SPROCKET_BAND // 2, bot - SPROCKET_BAND // 2):
        for i in range(n):
            cx = left + i * pitch + HOLE_W // 2
            d.rounded_rectangle(
                [cx - HOLE_W // 2, row_cy - HOLE_H // 2,
                 cx + HOLE_W // 2, row_cy + HOLE_H // 2],
                radius=14, fill=PAPER,
            )
    return img, origins


def place(img: Image.Image, origins, scenes: list[Path]) -> None:
    d = ImageDraw.Draw(img)
    for (x, y), scene in zip(origins, scenes):
        v = Image.open(scene).convert("RGBA").resize((WIN_SIZE, WIN_SIZE))
        # white-fill background behind the vignette so any transparency reads clean
        bg = Image.new("RGBA", (WIN_SIZE, WIN_SIZE), PAPER)
        bg.alpha_composite(v)
        img.alpha_composite(bg, (x, y))
        # thin frame border around the window
        d.rectangle([x, y, x + WIN_SIZE, y + WIN_SIZE],
                    outline=CHARCOAL, width=WIN_BORDER)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenes", required=True, help="comma-separated vignette IDs, e.g. V1,V2,V3")
    ap.add_argument("--out", required=True, help="output PNG path")
    args = ap.parse_args()

    ids = [s.strip() for s in args.scenes.split(",")]
    if len(ids) != WIN_COUNT:
        print(f"need exactly {WIN_COUNT} scenes, got {len(ids)}", file=sys.stderr)
        return 2
    scenes = []
    for i in ids:
        p = ART / f"{i}.png"
        if not p.is_file():
            print(f"missing vignette: {p}", file=sys.stderr)
            return 1
        scenes.append(p)

    img, origins = draw_strip()
    place(img, origins, scenes)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out)
    print(f"wrote {out}  ({W}x{H})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
